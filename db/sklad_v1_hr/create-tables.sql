/* ============================================================================
   СКЛАД NEW — КАДРОВАЯ БАЗА Sklad_v1_HR: таблицы
   ----------------------------------------------------------------------------
   Две таблицы:

     Специальность — Id (PK) + Название
     Сотрудник     — Id (PK), Guid (UNIQUE) + ФИО/адрес/телефон + специальность

   Guid — не просто идентификатор, а ключ связи между базами: основная база
   Sklad_v1 хранит его в Приход/Расход/Деньги как СотрудникGuid. Именно поэтому
   Guid заполняется при создании карточки и никогда не меняется, тогда как Id
   используется только внутри этой базы.
   ========================================================================== */

USE [Sklad_v1_HR];
GO

SET ANSI_NULLS ON;
GO
SET QUOTED_IDENTIFIER ON;
GO

/* ===========================================================================
   РАЗДЕЛ 0. СБРОС
   =========================================================================== */
IF OBJECT_ID(N'dbo.Сотрудник',     N'U') IS NOT NULL DROP TABLE dbo.Сотрудник;
IF OBJECT_ID(N'dbo.Специальность', N'U') IS NOT NULL DROP TABLE dbo.Специальность;
GO

/* ===========================================================================
   РАЗДЕЛ 1. СПРАВОЧНИКИ
   =========================================================================== */

/* ---------------------------------------------------------------------------
   Специальность (швея, обивщик, кладовщик ...)
   ------------------------------------------------------------------------- */
CREATE TABLE dbo.Специальность
(
    Id       int IDENTITY(1, 1) NOT NULL,
    Название nvarchar(50) NOT NULL,

    CONSTRAINT PK_Специальность PRIMARY KEY CLUSTERED (Id),
    CONSTRAINT UQ_Специальность_Название UNIQUE (Название)
);
GO

/* ---------------------------------------------------------------------------
   Сотрудник

   Guid  — уникальный ключ связи со складской базой Sklad_v1
   Имя   — ФИО (nvarchar(100): в legacy фамилия и имя в одно поле)
   ------------------------------------------------------------------------- */
CREATE TABLE dbo.Сотрудник
(
    Id              int IDENTITY(1, 1) NOT NULL,
    Guid            uniqueidentifier NOT NULL CONSTRAINT DF_Сотрудник_Guid DEFAULT (NEWID()),
    Имя             nvarchar(100) NOT NULL,
    Адрес           nvarchar(100) NULL,
    Телефон         nvarchar(18) NULL,
    СпециальностьId int NOT NULL,

    CONSTRAINT PK_Сотрудник PRIMARY KEY CLUSTERED (Id),
    CONSTRAINT UQ_Сотрудник_Guid UNIQUE (Guid),
    CONSTRAINT FK_Сотрудник_Специальность FOREIGN KEY (СпециальностьId)
        REFERENCES dbo.Специальность (Id)
        ON UPDATE CASCADE ON DELETE NO ACTION
);
GO

PRINT N'БД Sklad_v1_HR: таблицы созданы. Далее: create-indexes.sql, insert-reference-data.sql';
GO