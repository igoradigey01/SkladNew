   ----------------------------------------------------------------------------
   vw_ЗначенияХарактеристик — ЭФФЕКТИВНОЕ ЗНАЧЕНИЕ атрибута позиции.

   Логика та же, что в Microsoft Dynamics 365: атрибут заводится на категорию
   (здесь — вид номенклатуры) и наследуется всеми позициями этой категории;
   значение по умолчанию можно переопределить у конкретной позиции.

     Значение = ЗначениеХарактеристики (позиция)  — если строка есть;
     иначе   = Характеристика.ЗначениеПоУмолчанию (наследование от вида);
     иначе   = NULL (значение не задано).

   Колонка Источник показывает, откуда взято значение:
     «позиция»     — переопределено у позиции;
     «по умолчанию» — унаследовано от вида номенклатуры;
     «не задано»   — значения нет ни там, ни там.

   Скрипт идемпотентен: представление пересоздаётся при каждом запуске.
   ========================================================================== */

USE [Sklad-v4];
GO

SET ANSI_NULLS ON;
GO
SET QUOTED_IDENTIFIER ON;
GO

IF OBJECT_ID(N'dbo.vw_ЗначенияХарактеристик', N'V') IS NOT NULL
    DROP VIEW dbo.vw_ЗначенияХарактеристик;
GO

CREATE VIEW dbo.vw_ЗначенияХарактеристик
AS
SELECT  н.[Id]                    AS НоменклатураId,
        н.[Код],
        н.[Название]               AS НазваниеНоменклатуры,
        вн.[Id]                   AS ВидНоменклатурыId,
        вн.[Название]              AS НазваниеВида,
        х.[Id]                    AS ХарактеристикаId,
        х.[Название]               AS НазваниеХарактеристики,
        т.[Id]                    AS ТипЗначенияId,
        т.[Название]               AS ТипЗначения,
        х.[Порядок],
        х.[Обязательный],
        COALESCE(з.[Значение], х.[ЗначениеПоУмолчанию]) AS Значение,
        CASE
            WHEN з.[Id] IS NOT NULL THEN N'позиция'
            WHEN х.[ЗначениеПоУмолчанию] IS NOT NULL THEN N'по умолчанию'
            ELSE N'не задано'
        END                        AS Источник
FROM    dbo.Номенклатура AS н
INNER JOIN dbo.ВидНоменклатуры AS вн ON вн.[Id] = н.[ВидНоменклатурыId]
INNER JOIN dbo.Характеристика AS х ON х.[ВидНоменклатурыId] = н.[ВидНоменклатурыId]
INNER JOIN dbo.ТипЗначения AS т ON т.[Id] = х.[ТипЗначенияId]
LEFT JOIN dbo.ЗначениеХарактеристики AS з ON з.[НоменклатураId] = н.[Id]
                                           AND з.[ХарактеристикаId] = х.[Id]
WHERE   х.[Активен] = 1;
GO

PRINT N'Представление vw_ЗначенияХарактеристик создано';
GO
