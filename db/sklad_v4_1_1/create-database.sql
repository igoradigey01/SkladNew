/* ============================================================================
   СКЛАД NEW — БАЗА Sklad_v4.1.1: создание копии Sklad-v4.1
   ----------------------------------------------------------------------------
   Версия 4.1.1 = версия 4.1 + поля аудита во всех бизнес-таблицах.
   База создаётся копированием Sklad-v4.1 через BACKUP / RESTORE, чтобы
   сохранить не только схему, но и все данные, индексы, триггеры и
   представления.

   Запуск (из контейнера mssql_dev):
     /opt/mssql-tools18/bin/sqlcmd -S localhost -U sa -P '<пароль>' -C \
       -f 65001 -b -i create-database.sql
   ========================================================================== */

USE master;
GO

SET NOCOUNT ON;
SET XACT_ABORT ON;
GO

/* ---------------------------------------------------------------------------
   1. Удалить целевую базу, если она уже есть
   ------------------------------------------------------------------------- */
IF DB_ID(N'Sklad_v4.1.1') IS NOT NULL
BEGIN
    ALTER DATABASE [Sklad_v4.1.1] SET SINGLE_USER WITH ROLLBACK IMMEDIATE;
    DROP DATABASE [Sklad_v4.1.1];
END
GO

/* ---------------------------------------------------------------------------
   2. Резервная копия источника
   ------------------------------------------------------------------------- */
BACKUP DATABASE [Sklad-v4.1]
    TO DISK = N'/var/opt/mssql/data/Sklad-v4.1_for_v4.1.1.bak'
    WITH COPY_ONLY, INIT, CHECKSUM, STATS = 10;
GO

/* ---------------------------------------------------------------------------
   3. Восстановление под новым именем
   ------------------------------------------------------------------------- */
RESTORE DATABASE [Sklad_v4.1.1]
    FROM DISK = N'/var/opt/mssql/data/Sklad-v4.1_for_v4.1.1.bak'
    WITH MOVE N'Sklad-v4.1'     TO N'/var/opt/mssql/data/Sklad_v4.1.1.mdf',
         MOVE N'Sklad-v4.1_log' TO N'/var/opt/mssql/data/Sklad_v4.1.1_log.ldf',
         RECOVERY, REPLACE, STATS = 10;
GO

/* ---------------------------------------------------------------------------
   4. Проверка
   ------------------------------------------------------------------------- */
SELECT N'Sklad_v4.1.1' AS [База],
       COUNT(*) AS [Таблиц]
FROM [Sklad_v4.1.1].sys.tables
WHERE is_ms_shipped = 0;
GO

PRINT N'База Sklad_v4.1.1 создана. Далее: add-audit-columns.sql';
GO
