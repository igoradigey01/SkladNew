/* ============================================================================
   СКЛАД NEW — ОСНОВНАЯ БАЗА Sklad-v4: триггеры проверки значений
   ----------------------------------------------------------------------------
   Что делают:
     TR_Характеристика_Проверка        — проверяет ЗначениеПоУмолчанию
                                          характеристики по её типу;
     TR_ЗначениеХарактеристики_Проверка — проверяет значение атрибута позиции
                                          по типу характеристики;
     TR_СписокЗначений_Проверка         — не даёт удалить значение из списка,
                                          если оно уже используется.

   ПОЧЕМУ ТРИГГЕРЫ, А НЕ CHECK
   Правила зависят от типа значения, а тип лежит в другой таблице
   (ТипЗначения), а список допустимых значений — в третьей (СписокЗначений).
   В CHECK-ограничении подзапросы запрещены: «Subqueries are not allowed in
   this context. Only scalar expressions are allowed.» (SQL Server 2022).
   Проверено: TRY_CONVERT в CHECK разрешён, но тип всё равно недоступен —
   правила по типу можно реализовать только триггером.

   ПРАВИЛА ПО ТИПАМ ЗНАЧЕНИЯ
     Text   — длина значения не больше МаксимальнаяДлина;
     Number — значение преобразуется в число и лежит в [Минимум, Максимум];
     Date   — значение преобразуется в дату и лежит в [МинимальнаяДата,
              МаксимальнаяДата];
     Bool   — 0 / 1 / true / false / да / нет (регистр и пробелы не важны);
     List   — значение есть в СписокЗначений этой характеристики.

   ЗНАЧЕНИЕ ПО УМОЛЧАНИЮ И СПИСОК ЗНАЧЕНИЙ
   Для типа List умолчание проверяется только если список уже заполнен:
     • список значений ссылается на характеристику, поэтому заполнить его
       можно только после создания характеристики;
     • правильный порядок: создать характеристику -> заполнить
       СписокЗначений -> задать ЗначениеПоУмолчанию (второй UPDATE).
   Если умолчание задано, а список пуст, проверка откладывается; найти
   такие расхождения помогает запрос в verify-data.sql.

   Скрипт идемпотентен: триггеры пересоздаются при каждом запуске.
   ========================================================================== */

USE [Sklad-v4];
GO

SET ANSI_NULLS ON;
GO
SET QUOTED_IDENTIFIER ON;
GO

/* ===========================================================================
   1. ЗНАЧЕНИЕ ПО УМОЛЧАНИЮ ХАРАКТЕРИСТИКИ
   =========================================================================== */
IF OBJECT_ID(N'dbo.TR_Характеристика_Проверка', N'TR') IS NOT NULL
    DROP TRIGGER dbo.TR_Характеристика_Проверка;
GO

CREATE TRIGGER dbo.TR_Характеристика_Проверка
ON dbo.Характеристика
AFTER INSERT, UPDATE
AS
BEGIN
    SET NOCOUNT ON;

    IF EXISTS
    (
        SELECT 1
        FROM inserted AS i
        INNER JOIN dbo.Характеристика AS х ON х.[Id] = i.[Id]
        INNER JOIN dbo.ТипЗначения    AS т ON т.[Id] = х.[ТипЗначенияId]
        LEFT JOIN dbo.СписокЗначений AS с ON с.[ХарактеристикаId] = х.[Id]
                                          AND с.[Значение] = i.[ЗначениеПоУмолчанию]
        WHERE i.[ЗначениеПоУмолчанию] IS NOT NULL
          AND (   (т.[Название] = N'Text'
                   AND х.[МаксимальнаяДлина] IS NOT NULL
                   AND LEN(i.[ЗначениеПоУмолчанию]) > х.[МаксимальнаяДлина])
              OR (т.[Название] = N'Number'
                   AND TRY_CONVERT(decimal(18, 3), i.[ЗначениеПоУмолчанию]) IS NULL)
              OR (т.[Название] = N'Number' AND х.[Минимум] IS NOT NULL
                   AND TRY_CONVERT(decimal(18, 3), i.[ЗначениеПоУмолчанию]) < х.[Минимум])
              OR (т.[Название] = N'Number' AND х.[Максимум] IS NOT NULL
                   AND TRY_CONVERT(decimal(18, 3), i.[ЗначениеПоУмолчанию]) > х.[Максимум])
              OR (т.[Название] = N'Date'
                   AND TRY_CONVERT(date, i.[ЗначениеПоУмолчанию]) IS NULL)
              OR (т.[Название] = N'Date' AND х.[МинимальнаяДата] IS NOT NULL
                   AND TRY_CONVERT(date, i.[ЗначениеПоУмолчанию]) < х.[МинимальнаяДата])
              OR (т.[Название] = N'Date' AND х.[МаксимальнаяДата] IS NOT NULL
                   AND TRY_CONVERT(date, i.[ЗначениеПоУмолчанию]) > х.[МаксимальнаяДата])
              OR (т.[Название] = N'Bool'
                   AND LOWER(LTRIM(RTRIM(i.[ЗначениеПоУмолчанию])))
                       NOT IN (N'0', N'1', N'true', N'false', N'да', N'нет'))
              OR (т.[Название] = N'List'
                   AND EXISTS (SELECT 1 FROM dbo.СписокЗначений AS с2
                               WHERE с2.[ХарактеристикаId] = i.[Id])
                   AND с.[Id] IS NULL))
    )
    BEGIN
        ROLLBACK TRANSACTION;
        THROW 51001, N'Значение по умолчанию не соответствует типу характеристики', 1;
    END
END
GO

/* ===========================================================================
   2. ЗНАЧЕНИЕ АТРИБУТА У ПОЗИЦИИ
   =========================================================================== */
IF OBJECT_ID(N'dbo.TR_ЗначениеХарактеристики_Проверка', N'TR') IS NOT NULL
    DROP TRIGGER dbo.TR_ЗначениеХарактеристики_Проверка;
GO

CREATE TRIGGER dbo.TR_ЗначениеХарактеристики_Проверка
ON dbo.ЗначениеХарактеристики
AFTER INSERT, UPDATE
AS
BEGIN
    SET NOCOUNT ON;

    IF EXISTS
    (
        SELECT 1
        FROM inserted AS i
        INNER JOIN dbo.Характеристика AS х ON х.[Id] = i.[ХарактеристикаId]
        INNER JOIN dbo.ТипЗначения    AS т ON т.[Id] = х.[ТипЗначенияId]
        LEFT JOIN dbo.СписокЗначений AS с ON с.[ХарактеристикаId] = х.[Id]
                                          AND с.[Значение] = i.[Значение]
        WHERE    (т.[Название] = N'Text'
                  AND х.[МаксимальнаяДлина] IS NOT NULL
                  AND LEN(i.[Значение]) > х.[МаксимальнаяДлина])
             OR (т.[Название] = N'Number'
                  AND TRY_CONVERT(decimal(18, 3), i.[Значение]) IS NULL)
             OR (т.[Название] = N'Number' AND х.[Минимум] IS NOT NULL
                  AND TRY_CONVERT(decimal(18, 3), i.[Значение]) < х.[Минимум])
             OR (т.[Название] = N'Number' AND х.[Максимум] IS NOT NULL
                  AND TRY_CONVERT(decimal(18, 3), i.[Значение]) > х.[Максимум])
             OR (т.[Название] = N'Date'
                  AND TRY_CONVERT(date, i.[Значение]) IS NULL)
             OR (т.[Название] = N'Date' AND х.[МинимальнаяДата] IS NOT NULL
                  AND TRY_CONVERT(date, i.[Значение]) < х.[МинимальнаяДата])
             OR (т.[Название] = N'Date' AND х.[МаксимальнаяДата] IS NOT NULL
                  AND TRY_CONVERT(date, i.[Значение]) > х.[МаксимальнаяДата])
             OR (т.[Название] = N'Bool'
                  AND LOWER(LTRIM(RTRIM(i.[Значение])))
                      NOT IN (N'0', N'1', N'true', N'false', N'да', N'нет'))
             OR (т.[Название] = N'List' AND с.[Id] IS NULL)
    )
    BEGIN
        ROLLBACK TRANSACTION;
        THROW 51002, N'Значение характеристики не соответствует её типу', 1;
    END
END
GO

/* ===========================================================================
   3. ЗАЩИТА СПИСКА ЗНАЧЕНИЙ
   Значение из списка нельзя удалить, если оно уже используется: либо
   является значением по умолчанию, либо записано у позиции.
   =========================================================================== */
IF OBJECT_ID(N'dbo.TR_СписокЗначений_Проверка', N'TR') IS NOT NULL
    DROP TRIGGER dbo.TR_СписокЗначений_Проверка;
GO

CREATE TRIGGER dbo.TR_СписокЗначений_Проверка
ON dbo.СписокЗначений
AFTER DELETE
AS
BEGIN
    SET NOCOUNT ON;

    IF EXISTS
    (
        SELECT 1
        FROM deleted AS d
        INNER JOIN dbo.Характеристика AS х ON х.[Id] = d.[ХарактеристикаId]
        WHERE х.[ЗначениеПоУмолчанию] = d.[Значение]
           OR EXISTS (SELECT 1 FROM dbo.ЗначениеХарактеристики AS з
                      WHERE з.[ХарактеристикаId] = d.[ХарактеристикаId]
                        AND з.[Значение] = d.[Значение])
    )
    BEGIN
        ROLLBACK TRANSACTION;
        THROW 51003, N'Значение из списка уже используется — удалить его нельзя', 1;
    END
END
GO

PRINT N'Триггеры Sklad-v4 созданы';
GO
