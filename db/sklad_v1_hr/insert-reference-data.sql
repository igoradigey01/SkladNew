USE [Sklad_v1_HR];
GO

SET NOCOUNT ON;
GO
SET XACT_ABORT ON;
GO

BEGIN TRANSACTION;
GO

/* ---------------------------------------------------------------------------
   Специальности
   ------------------------------------------------------------------------- */
INSERT INTO dbo.Специальность (Название)
SELECT v.Название
FROM (VALUES (N'Швея'),
             (N'Обивщик'),
             (N'Сборщик'),
             (N'Упаковщик'),
             (N'Мастер участка'),
             (N'Кладовщик')) AS v (Название)
WHERE NOT EXISTS (SELECT 1 FROM dbo.Специальность AS t WHERE t.Название = v.Название);
GO

/* ---------------------------------------------------------------------------
   Демо-сотрудник: нужен, чтобы в основной базе было что показать
   в СотрудникGuid и в выплатах (Деньги.OperationType = 3).
   ------------------------------------------------------------------------- */
INSERT INTO dbo.Сотрудник (Guid, Имя, Адрес, Телефон, СпециальностьId)
SELECT CONVERT(uniqueidentifier, 'C0FFEE00-0000-0000-0000-000000000001'),
       N'Сидорова Мария Ивановна',
       N'г. Барнаул',
       N'89180011223',
       sp.Id
FROM dbo.Специальность AS sp
WHERE sp.Название = N'Мастер участка'
  AND NOT EXISTS (SELECT 1 FROM dbo.Сотрудник AS t WHERE t.Имя = N'Сидорова Мария Ивановна');
GO

COMMIT TRANSACTION;
GO

/* --- Итог --- */
SELECT N'Специальность' AS [Таблица], COUNT(*) AS [Записей] FROM dbo.Специальность
UNION ALL SELECT N'Сотрудник', COUNT(*) FROM dbo.Сотрудник;
GO

SELECT Id, Guid, Имя, СпециальностьId FROM dbo.Сотрудник ORDER BY Id;
GO

PRINT N'Кадровая база Sklad_v1_HR наполнена';
GO