/* ============================================================================
   СКЛАД NEW — ОСНОВНАЯ БАЗА Sklad-v4.1: представления
   ----------------------------------------------------------------------------
   vw_ЗначенияХарактеристик — ЭФФЕКТИВНОЕ ЗНАЧЕНИЕ атрибута позиции.
   vw_БалансСделки         — отгружено / оплачено / долг по сделке.
   vw_БалансКлиента        — свод по клиенту и проверка предела кредита.
   vw_ДвиженияПоСделке     — документы сделки с нарастающим итогом долга.

   ПОЧЕМУ ДОЛГ НЕ ХРАНИТСЯ
   Долг — производная величина: он всегда равен «отгружено минус оплачено».
   В эталоне Долг хранился и у 70 из 150 сделок не сходился с движениями.
   Здесь он вычисляется в представлении, поэтому рассинхронизация невозможна.

   Логика vw_ЗначенияХарактеристик: атрибут заводится на категорию
   (здесь — вид номенклатуры) и наследуется всеми позициями этой категории;
   значение по умолчанию можно переопределить у конкретной позиции.

     Значение = ЗначениеХарактеристики (позиция)  — если строка есть;
     иначе   = Характеристика.ЗначениеПоУмолчанию (наследование от вида);
     иначе   = NULL (значение не задано).

   Колонка Источник показывает, откуда взято значение:
     «позиция»     — переопределено у позиции;
     «по умолчанию» — унаследовано от вида номенклатуры;
     «не задано»   — значения нет ни там, ни там.

   Скрипт идемпотентен: представления пересоздаются при каждом запуске.
   ========================================================================== */

USE [Sklad-v4.1];
GO

SET ANSI_NULLS ON;
GO
SET QUOTED_IDENTIFIER ON;
GO

IF OBJECT_ID(N'dbo.vw_ЗначенияХарактеристик', N'V') IS NOT NULL
    DROP VIEW dbo.vw_ЗначенияХарактеристик;
GO

CREATE VIEW dbo.vw_ЗначенияХарактеристик
AS
SELECT  н.[Id]                    AS НоменклатураId,
        н.[Код],
        н.[Название]               AS НазваниеНоменклатуры,
        вн.[Id]                   AS ВидНоменклатурыId,
        вн.[Название]              AS НазваниеВида,
        х.[Id]                    AS ХарактеристикаId,
        х.[Название]               AS НазваниеХарактеристики,
        т.[Id]                    AS ТипЗначенияId,
        т.[Название]               AS ТипЗначения,
        х.[Порядок],
        х.[Обязательный],
        COALESCE(з.[Значение], х.[ЗначениеПоУмолчанию]) AS Значение,
        CASE
            WHEN з.[Id] IS NOT NULL THEN N'позиция'
            WHEN х.[ЗначениеПоУмолчанию] IS NOT NULL THEN N'по умолчанию'
            ELSE N'не задано'
        END                        AS Источник
FROM    dbo.Номенклатура AS н
INNER JOIN dbo.ВидНоменклатуры AS вн ON вн.[Id] = н.[ВидНоменклатурыId]
INNER JOIN dbo.Характеристика AS х ON х.[ВидНоменклатурыId] = н.[ВидНоменклатурыId]
INNER JOIN dbo.ТипЗначения AS т ON т.[Id] = х.[ТипЗначенияId]
LEFT JOIN dbo.ЗначениеХарактеристики AS з ON з.[НоменклатураId] = н.[Id]
                                           AND з.[ХарактеристикаId] = х.[Id]
WHERE   х.[Активен] = 1;
GO

/* ===========================================================================
   ВЗАИМОРАСЧЁТЫ
   =========================================================================== */

/* ---------------------------------------------------------------------------
   vw_БалансСделки — главный отчёт по сделке.

   Отгружено = сумма строк Расход по всем накладным сделки.
   Оплачено  = полученные деньги (OperationType 1 и 4) минус возвраты
               клиенту (OperationType 2).
   Долг      = Отгружено - Оплачено. Положительный — клиент должен,
               отрицательный — переплата (аванс).
   Переплата = max(0, Оплачено - Отгружено) — для удобства отчётов.

   Все суммы берутся только по одной сделке: история других сделок клиента
   не читается.
   ------------------------------------------------------------------------- */
IF OBJECT_ID(N'dbo.vw_БалансСделки', N'V') IS NOT NULL
    DROP VIEW dbo.vw_БалансСделки;
GO

CREATE VIEW dbo.vw_БалансСделки
AS
WITH отгрузка AS
(
    SELECT  n.[КодСделки],
            COUNT(DISTINCT n.[Id]) AS Накладных,
            CAST(ISNULL(SUM(r.[Sum]), 0) AS decimal(18, 2)) AS Отгружено
    FROM    dbo.НакладнаяРасход AS n
    LEFT JOIN dbo.Расход AS r ON r.[НакладнаяId] = n.[Id]
    GROUP BY n.[КодСделки]
),
оплата AS
(
    SELECT  m.[КодСделки],
            COUNT(*) AS Платежей,
            CAST(ISNULL(SUM(
                CASE WHEN m.[OperationType] IN (1, 4) THEN m.[Sum]
                     WHEN m.[OperationType] = 2      THEN -m.[Sum]
                     ELSE 0
                END), 0) AS decimal(18, 2)) AS Оплачено
    FROM    dbo.Деньги AS m
    WHERE   m.[КодСделки] IS NOT NULL
    GROUP BY m.[КодСделки]
)
SELECT  s.[КодСделки],
        s.[НомерСделки],
        s.[КлиентId],
        k.[Псевдоним]                       AS Клиент,
        s.[Дата],
        s.[Активна],
        ISNULL(o.[Накладных], 0)            AS Накладных,
        ISNULL(o.[Отгружено], 0)            AS Отгружено,
        ISNULL(p.[Платежей], 0)             AS Платежей,
        ISNULL(p.[Оплачено], 0)             AS Оплачено,
        CAST(ISNULL(o.[Отгружено], 0) - ISNULL(p.[Оплачено], 0) AS decimal(18, 2)) AS Долг,
        CAST(CASE WHEN ISNULL(p.[Оплачено], 0) > ISNULL(o.[Отгружено], 0)
                  THEN ISNULL(p.[Оплачено], 0) - ISNULL(o.[Отгружено], 0)
                  ELSE 0
             END AS decimal(18, 2))         AS Переплата
FROM    dbo.Сделка AS s
INNER JOIN dbo.Клиент AS k ON k.[Id] = s.[КлиентId]
LEFT JOIN отгрузка AS o ON o.[КодСделки] = s.[КодСделки]
LEFT JOIN оплата  AS p ON p.[КодСделки] = s.[КодСделки];
GO

/* ---------------------------------------------------------------------------
   vw_БалансКлиента — свод по всем сделкам клиента.

   Долг клиента — сумма долгов его сделок. Сделки не фильтруются по
   активности: закрытая сделка с непогашенным долгом всё равно должна
   попадать в расчёт.
   ------------------------------------------------------------------------- */
IF OBJECT_ID(N'dbo.vw_БалансКлиента', N'V') IS NOT NULL
    DROP VIEW dbo.vw_БалансКлиента;
GO

CREATE VIEW dbo.vw_БалансКлиента
AS
SELECT  k.[Id]                  AS КлиентId,
        k.[Псевдоним]           AS Клиент,
        k.[ПределКредита],
        k.[Активен],
        COUNT(s.[КодСделки])    AS Сделок,
        ISNULL(SUM(CASE WHEN s.[Активна] = 1 THEN 1 ELSE 0 END), 0) AS АктивныхСделок,
        CAST(ISNULL(SUM(b.[Отгружено]), 0) AS decimal(18, 2)) AS Отгружено,
        CAST(ISNULL(SUM(b.[Оплачено]),  0) AS decimal(18, 2)) AS Оплачено,
        CAST(ISNULL(SUM(b.[Долг]),      0) AS decimal(18, 2)) AS Долг,
        CAST(ISNULL(SUM(b.[Переплата]), 0) AS decimal(18, 2)) AS Переплата,
        CASE WHEN ISNULL(SUM(b.[Долг]), 0) > k.[ПределКредита]
             THEN 1 ELSE 0
        END                     AS ПревышенЛимит
FROM    dbo.Клиент AS k
LEFT JOIN dbo.Сделка AS s ON s.[КлиентId] = k.[Id]
LEFT JOIN dbo.vw_БалансСделки AS b ON b.[КодСделки] = s.[КодСделки]
GROUP BY k.[Id], k.[Псевдоним], k.[ПределКредита], k.[Активен];
GO

/* ---------------------------------------------------------------------------
   vw_ДвиженияПоСделке — отчёт «документ за документом» с нарастающим итогом,
   как в задаче: сначала отгрузка, потом оплата, в конце — баланс сделки.

   СуммаОтгрузки и СуммаОплаты разнесены по колонкам, ВлияниеНаДолг
   показывает знак: отгрузка увеличивает долг, оплата уменьшает, возврат
   клиенту снова увеличивает.
   ------------------------------------------------------------------------- */
IF OBJECT_ID(N'dbo.vw_ДвиженияПоСделке', N'V') IS NOT NULL
    DROP VIEW dbo.vw_ДвиженияПоСделке;
GO

CREATE VIEW dbo.vw_ДвиженияПоСделке
AS
WITH движения AS
(
    SELECT  n.[КодСделки],
            n.[КлиентId],
            n.[Дата]                    AS ДатаДокумента,
            N'Отгрузка'                 AS ВидДокумента,
            n.[Номер]                   AS Документ,
            n.[Id]                      AS ДокументId,
            CAST(ISNULL(SUM(r.[Sum]), 0) AS decimal(18, 2)) AS СуммаОтгрузки,
            CAST(0 AS decimal(18, 2))   AS СуммаОплаты,
            CAST(ISNULL(SUM(r.[Sum]), 0) AS decimal(18, 2)) AS ВлияниеНаДолг
    FROM    dbo.НакладнаяРасход AS n
    LEFT JOIN dbo.Расход AS r ON r.[НакладнаяId] = n.[Id]
    GROUP BY n.[КодСделки], n.[КлиентId], n.[Дата], n.[Номер], n.[Id]

    UNION ALL

    SELECT  m.[КодСделки],
            m.[CounterpartyId],
            m.[Date],
            N'Оплата',
            ISNULL(m.[НомерДокумента], CONCAT(N'Платёж #', m.[Id])),
            m.[Id],
            CAST(0 AS decimal(18, 2)),
            CAST(m.[Sum] AS decimal(18, 2)),
            CAST(CASE WHEN m.[OperationType] = 2 THEN -m.[Sum] ELSE m.[Sum] END AS decimal(18, 2))
    FROM    dbo.Деньги AS m
    WHERE   m.[КодСделки] IS NOT NULL
)
SELECT  d.[КодСделки],
        s.[НомерСделки],
        d.[КлиентId],
        k.[Псевдоним]           AS Клиент,
        d.[ДатаДокумента],
        d.[ВидДокумента],
        d.[Документ],
        d.[СуммаОтгрузки],
        d.[СуммаОплаты],
        SUM(d.[ВлияниеНаДолг]) OVER
        (
            PARTITION BY d.[КодСделки]
            ORDER BY d.[ДатаДокумента], d.[ВидДокумента] DESC, d.[ДокументId]
            ROWS UNBOUNDED PRECEDING
        )                       AS ДолгНарастающимИтогом
FROM    движения AS d
INNER JOIN dbo.Сделка AS s ON s.[КодСделки] = d.[КодСделки]
INNER JOIN dbo.Клиент AS k ON k.[Id] = d.[КлиентId];
GO

PRINT N'Представления Sklad-v4.1 созданы';
GO
