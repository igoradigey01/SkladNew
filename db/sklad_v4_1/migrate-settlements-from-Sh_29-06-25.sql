/* ============================================================================
   СКЛАД NEW — ОСНОВНАЯ БАЗА Sklad-v4.1: перенос взаиморасчётов из эталона
   ----------------------------------------------------------------------------
   Что переносится:
     • КлиентМеткаРасчет  -> Сделка (150 строк, ровная нумерация R-000001…R-000150);
     • НакладнаяРасход    -> шапка НакладнаяРасход (1400 строк);
     • связь метка -> сделка проставляется в шапке накладной;
     • Расход.НакладнаяId  — строки привязываются к своей шапке по UETR;
     • Деньги.КодСделки    — платежи привязываются к сделке по метке.

   ПОРЯДОК ЗАПУСКА
   Сначала migrate-movements-from-Sh_29-06-25.sql (он заполняет Расход и
   Деньги), затем этот скрипт. Если запустить наоборот, шапки создадутся,
   но строки останутся без НакладнаяId — тогда скрипт нужно повторить.

   ИДЕНТИФИКАТОРЫ
   КодСделки детерминирован: E0000000-0000-0000-0000-{id метки}.
   UETR накладной совпадает с UETR её строк в Расход: B0000000-...-{id}.
   UETR платежа совпадает с UETR строки в Деньги: C0000000-...-{id}.
   Благодаря этому повторный запуск не дублирует данные.

   ЧЕГО НЕТ В ЭТАЛОНЕ
   Номер платёжного документа, комментарии к накладным и признак активности
   сделки. Перенесённые строки получают NULL/1, новые заполняет приложение.
   ========================================================================== */

USE [Sklad-v4.1];
GO

/* Индекс на вычисляемой колонке и фильтрованный индекс требуют этих SET-опций
   при любой записи в Сделка. sqlcmd по умолчанию выключает QUOTED_IDENTIFIER,
   поэтому задаём явно. */
SET ANSI_NULLS ON;
GO
SET ANSI_PADDING ON;
GO
SET ANSI_WARNINGS ON;
GO
SET ARITHABORT ON;
GO
SET CONCAT_NULL_YIELDS_NULL ON;
GO
SET QUOTED_IDENTIFIER ON;
GO
SET NUMERIC_ROUNDABORT OFF;
GO

SET XACT_ABORT ON;
GO

BEGIN TRANSACTION;
GO

/* ===========================================================================
   1. СДЕЛКИ: КлиентМеткаРасчет -> Сделка
   ---------------------------------------------------------------------------
   Номер берётся из ROW_NUMBER() по всему эталону, а не из id метки:
   в эталоне id идут с пропусками, а нужен ровный ряд 1..150.
   Фильтр NOT EXISTS применяется после нумерации, поэтому частичный повтор
   не сдвигает уже выданные номера.
   =========================================================================== */
WITH src AS
(
    SELECT  m.[id],
            ROW_NUMBER() OVER (ORDER BY m.[id]) AS rn,
            m.[клиентId],
            m.[дата],
            m.[коментарий]
    FROM    [Sh_29-06-25].dbo.[КлиентМеткаРасчет] AS m
)
INSERT INTO dbo.Сделка (НомерСделки, КодСделки, КлиентId, Дата, Комментарий, LegacyId, ДатаСоздания, Активна)
SELECT  N'R-' + RIGHT('000000' + CAST(src.rn AS varchar(10)), 6),
        CONVERT(uniqueidentifier,
                CONCAT('E0000000-0000-0000-0000-',
                       RIGHT('000000000000' + CAST(src.[id] AS varchar(12)), 12))),
        src.[клиентId],
        src.[дата],
        NULLIF(LTRIM(RTRIM(src.[коментарий])), N'none'),
        src.[id],
        GETDATE(),
        1
FROM    src
WHERE   NOT EXISTS (SELECT 1 FROM dbo.Сделка AS s WHERE s.[LegacyId] = src.[id]);
GO

/* ===========================================================================
   2. ШАПКИ НАКЛАДНЫХ: НакладнаяРасход -> НакладнаяРасход
   =========================================================================== */
WITH src AS
(
    SELECT  n.[id],
            n.[номер],
            n.[дата],
            n.[клиентId],
            n.[меткаId],
            CONVERT(uniqueidentifier,
                    CONCAT('B0000000-0000-0000-0000-',
                           RIGHT('000000000000' + CAST(n.[id] AS varchar(12)), 12))) AS UETR
    FROM    [Sh_29-06-25].dbo.[НакладнаяРасход] AS n
)
INSERT INTO dbo.НакладнаяРасход (UETR, Номер, Дата, КлиентId, КодСделки, Комментарий)
SELECT  src.UETR,
        src.[номер],
        src.[дата],
        src.[клиентId],
        s.[КодСделки],
        NULL
FROM    src
INNER JOIN dbo.Сделка AS s ON s.[LegacyId] = src.[меткаId]
WHERE   NOT EXISTS (SELECT 1 FROM dbo.НакладнаяРасход AS h WHERE h.[UETR] = src.UETR);
GO

/* ===========================================================================
   3. СТРОКИ РАСХОДА -> ШАПКА ПО UETR
   =========================================================================== */
UPDATE r
SET    r.[НакладнаяId] = h.[Id]
FROM   dbo.Расход AS r
INNER JOIN dbo.НакладнаяРасход AS h ON h.[UETR] = r.[UETR]
WHERE  r.[НакладнаяId] IS NULL;
GO

/* ===========================================================================
   4. ПЛАТЕЖИ -> СДЕЛКА ПО МЕТКЕ
   =========================================================================== */
WITH src AS
(
    SELECT  d.[id],
            d.[меткаId],
            CONVERT(uniqueidentifier,
                    CONCAT('C0000000-0000-0000-0000-',
                           RIGHT('000000000000' + CAST(d.[id] AS varchar(12)), 12))) AS UETR
    FROM    [Sh_29-06-25].dbo.[КлиентДеньги] AS d
)
UPDATE m
SET    m.[КодСделки] = s.[КодСделки]
FROM   dbo.Деньги AS m
INNER JOIN src ON src.[UETR] = m.[UETR]
INNER JOIN dbo.Сделка AS s ON s.[LegacyId] = src.[меткаId]
WHERE  m.[КодСделки] IS NULL;
GO

/* ===========================================================================
   5. ПРОДОЛЖИТЬ НУМЕРАЦИЮ ПОСЛЕ ПЕРЕНОСА
   ---------------------------------------------------------------------------
   Перенесённые сделки получили номера вручную, последовательность при этом
   не двигалась. Ставим её на MAX+1, чтобы новая сделка получила R-000151.
   =========================================================================== */
DECLARE @next int =
(
    SELECT ISNULL(MAX(TRY_CAST(SUBSTRING([НомерСделки], 3, 6) AS int)), 0) + 1
    FROM   dbo.Сделка
);

DECLARE @sql nvarchar(200) =
    N'ALTER SEQUENCE dbo.seq_НомерСделки RESTART WITH ' + CAST(@next AS nvarchar(10)) + N';';

EXEC (@sql);
GO

COMMIT TRANSACTION;
GO

/* --- Итог --- */
SELECT  N'Сделка'            AS [Таблица],
        COUNT(*)             AS [Строк],
        MIN([НомерСделки]) + N'…' + MAX([НомерСделки]) AS [Диапазон номеров]
FROM    dbo.Сделка
UNION ALL
SELECT  N'НакладнаяРасход', COUNT(*), NULL FROM dbo.НакладнаяРасход
UNION ALL
SELECT  N'Расход с шапкой', COUNT(*), NULL FROM dbo.Расход WHERE НакладнаяId IS NOT NULL
UNION ALL
SELECT  N'Деньги со сделкой', COUNT(*), NULL FROM dbo.Деньги WHERE КодСделки IS NOT NULL;
GO

SELECT  MIN([НомерСделки]) AS [Первый],
        MAX([НомерСделки]) AS [Последний],
        COUNT(*)           AS [Всего],
        COUNT(DISTINCT [НомерСделки]) AS [Уникальных номеров]
FROM    dbo.Сделка;
GO

PRINT N'Взаиморасчёты эталона перенесены в Sklad-v4.1';
GO
